'use strict'
// Local Paper server management: write config, start, stop, probe.
// This is the "set" server, separate from any production server. It runs on
// its own port (default 25566), offline mode (bots need no accounts), flat
// world with grass at ground_y, no mobs, no daylight cycle.
const fs = require('fs')
const net = require('net')
const path = require('path')
const { spawn } = require('child_process')
const U = require('../util')

const SERVER_DIR = path.join(U.ROOT, 'server')
const MC_VERSION = '1.21.4'
const DEFAULTS = { host: '127.0.0.1', port: 25566, groundY: 64, javaXmx: '3G', terrain: 'flat', seed: 'mcmovie' }

function config () {
  const f = path.join(SERVER_DIR, 'mcmovie-server.json')
  return U.exists(f) ? { ...DEFAULTS, ...U.readJson(f) } : { ...DEFAULTS }
}

function flatPreset (groundY) {
  // world bottom is -64; stack layers so the grass block sits at groundY
  const stone = groundY - (-64) - 1 - 3 - 1 + 1 // bedrock(1) + stone + dirt(3) + grass(1) spans -64..groundY
  const layers = [
    { block: 'minecraft:bedrock', height: 1 },
    { block: 'minecraft:stone', height: stone },
    { block: 'minecraft:dirt', height: 3 },
    { block: 'minecraft:grass_block', height: 1 }
  ]
  return JSON.stringify({ layers, biome: 'minecraft:plains' })
}

function propEscape (s) { return s.replace(/:/g, '\\:').replace(/=/g, '\\=') }

function setup (opts = {}) {
  // only options that were actually given override the saved configuration
  const given = Object.fromEntries(Object.entries(opts).filter(([, v]) => v !== undefined))
  const cfg = { ...config(), ...given }
  fs.mkdirSync(SERVER_DIR, { recursive: true })
  U.writeJson(path.join(SERVER_DIR, 'mcmovie-server.json'), { host: cfg.host, port: cfg.port, groundY: cfg.groundY, javaXmx: cfg.javaXmx, terrain: cfg.terrain, seed: cfg.seed })
  const natural = cfg.terrain === 'normal'
  U.calmSkinLookups(SERVER_DIR)
  fs.writeFileSync(path.join(SERVER_DIR, 'eula.txt'), 'eula=true\n')
  const props = {
    'server-port': cfg.port,
    'server-ip': cfg.host === '0.0.0.0' ? '' : cfg.host,
    'online-mode': false,
    'level-name': natural ? 'set_terrain' : 'set',
    'level-type': natural ? 'minecraft:normal' : 'minecraft:flat',
    'level-seed': natural ? cfg.seed : '',
    'generator-settings': natural ? '{}' : flatPreset(cfg.groundY),
    gamemode: 'creative',
    difficulty: 'peaceful',
    // true only so a monster can be summoned at all (the outro's creeper): on peaceful none
    // exists, and bukkit.yml below keeps any from spawning by itself
    'spawn-monsters': true,
    'spawn-animals': natural,
    'spawn-npcs': false,
    'generate-structures': false,
    'allow-flight': true,
    'allow-nether': false,
    'view-distance': 10,
    'simulation-distance': 10,
    'max-players': 200,
    'spawn-protection': 0,
    'enable-command-block': true,
    'enforce-secure-profile': false,
    'network-compression-threshold': -1,
    'sync-chunk-writes': false,
    'max-tick-time': -1,
    motd: 'mcmovie set server',
    'enable-rcon': false
  }
  fs.writeFileSync(path.join(SERVER_DIR, 'server.properties'),
    '# generated by mcmovie server:setup\n' + Object.entries(props).map(([k, v]) => `${k}=${propEscape(String(v))}`).join('\n') + '\n')
  fs.writeFileSync(path.join(SERVER_DIR, 'spigot.yml'), `# generated by mcmovie; Paper fills in the rest
settings:
  moved-too-quickly-multiplier: 100.0
  moved-wrongly-threshold: 100.0
world-settings:
  default:
    entity-tracking-range:
      players: 256
      animals: 256
      monsters: 256
      misc: 256
      display: 256
      other: 256
    entity-activation-range:
      animals: 256
      monsters: 256
      raiders: 256
      misc: 256
      water: 256
      villagers: 256
      flying-monsters: 256
`)
  fs.writeFileSync(path.join(SERVER_DIR, 'bukkit.yml'), `settings:
  allow-end: false
  warn-on-overload: false
spawn-limits:
  monsters: 0
  animals: ${natural ? 10 : 0}
  water-animals: 0
  water-ambient: 0
  water-underground-creature: 0
  axolotls: 0
  ambient: 0
`)
  // Op the Camera/director bot so it can run commands.
  const ops = [{ uuid: U.offlineUUID('Camera'), name: 'Camera', level: 4, bypassesPlayerLimit: true }]
  U.writeJson(path.join(SERVER_DIR, 'ops.json'), ops)
  return cfg
}

function jarPath () {
  const j = path.join(SERVER_DIR, 'paper.jar')
  return U.exists(j) ? j : null
}

function isUp (host, port, timeoutMs = 800) {
  return new Promise(resolve => {
    const s = net.connect({ host, port })
    const done = (v) => { try { s.destroy() } catch {} resolve(v) }
    s.once('connect', () => done(true))
    s.once('error', () => done(false))
    setTimeout(() => done(false), timeoutMs)
  })
}

// Start the server as a child process. Resolves with a handle once the server
// prints "Done". The handle has stop(), send(cmd), and the child process.
function start (opts = {}) {
  const cfg = { ...config(), ...opts }
  if (!jarPath()) throw new Error(`server/paper.jar missing. Run: mcmovie server:setup`)
  if (!U.exists(path.join(SERVER_DIR, 'eula.txt'))) setup(cfg)
  fs.mkdirSync(path.join(SERVER_DIR, 'logs'), { recursive: true })
  const logFile = fs.createWriteStream(path.join(SERVER_DIR, 'logs', 'console.log'), { flags: 'a' })
  const args = [`-Xms1G`, `-Xmx${cfg.javaXmx}`, '-XX:+UseG1GC', '-Dcom.mojang.eula.agree=true', '-jar', jarPath(), '--nogui']
  const child = spawn('java', args, { cwd: SERVER_DIR, stdio: ['pipe', 'pipe', 'pipe'] })
  fs.writeFileSync(path.join(SERVER_DIR, 'server.pid'), String(child.pid))
  const handle = {
    child,
    cfg,
    ready: false,
    send (cmd) { child.stdin.write(cmd + '\n') },
    stop () {
      return new Promise(resolve => {
        if (child.exitCode !== null) return resolve()
        child.once('exit', () => resolve())
        try { child.stdin.write('stop\n') } catch { child.kill() }
        const killTimer = setTimeout(() => { if (child.exitCode === null) child.kill('SIGKILL') }, 30000)
        child.once('exit', () => clearTimeout(killTimer))
      })
    }
  }
  return new Promise((resolve, reject) => {
    let buf = ''
    // cancelled as soon as the server is up or gone, so it never keeps the process alive
    const startTimer = setTimeout(() => { if (!handle.ready) reject(new Error('server did not become ready in 180s')) }, 180000)
    const onData = (d) => {
      logFile.write(d)
      if (opts.echo) process.stdout.write(d)
      buf += d.toString()
      const lines = buf.split('\n'); buf = lines.pop()
      for (const line of lines) {
        if (!handle.ready && /Done \(/.test(line)) { handle.ready = true; clearTimeout(startTimer); resolve(handle) }
        if (/You need to agree to the EULA/.test(line)) reject(new Error('EULA not accepted'))
      }
    }
    child.stdout.on('data', onData)
    child.stderr.on('data', onData)
    child.on('exit', (code) => {
      clearTimeout(startTimer)
      try { fs.unlinkSync(path.join(SERVER_DIR, 'server.pid')) } catch {}
      if (!handle.ready) reject(new Error(`server exited with code ${code} before ready; see server/logs/console.log`))
    })
  })
}

async function stopRunning () {
  const pidFile = path.join(SERVER_DIR, 'server.pid')
  if (!U.exists(pidFile)) return false
  const pid = parseInt(fs.readFileSync(pidFile, 'utf8'), 10)
  try { process.kill(pid, 'SIGTERM') } catch { return false }
  for (let i = 0; i < 60; i++) {
    await U.sleep(500)
    try { process.kill(pid, 0) } catch { return true }
  }
  try { process.kill(pid, 'SIGKILL') } catch {}
  return true
}

module.exports = { SERVER_DIR, MC_VERSION, config, setup, start, isUp, stopRunning, jarPath, flatPreset }
